import { openPrWithFile } from "../github";
import type { AgentContext, BrdResult, BuildResult, PrResult } from "./types";

/**
 * PR agent. Opens a pull request for the build against the company's connected
 * repo.
 *
 * When a GitHub token + repo are connected, this opens a REAL pull request: it
 * creates a branch, commits the approved BRD as a "requirements" doc, and opens
 * the PR. (Once the builder writes real code, that content replaces the doc.)
 *
 * With no token/repo it falls back to a synthesized compare URL so the pipeline
 * still completes in a demo.
 */
export async function runPr(
  ctx: AgentContext,
  build: BuildResult,
  brd: BrdResult
): Promise<PrResult> {
  const title = `[Gauge] ${ctx.request.title}`;

  if (ctx.githubToken && ctx.repo) {
    await ctx.log(`Opening a real pull request against ${ctx.repo}.`);
    try {
      const filePath = `docs/gauge/${ctx.request.id}.md`;
      const opened = await openPrWithFile({
        token: ctx.githubToken,
        repo: ctx.repo,
        branch: build.branch,
        filePath,
        fileContents: brdDoc(ctx, brd),
        commitMessage: `Gauge requirements: ${ctx.request.title}`,
        prTitle: title,
        prBody: prBody(ctx, brd),
      });
      await ctx.log(`Opened PR #${opened.number}.`, { url: opened.url });
      return { number: opened.number, url: opened.url, title };
    } catch (err) {
      await ctx.log(
        `Real PR creation failed (${(err as Error).message}); using a compare URL instead.`
      );
    }
  } else {
    await ctx.log(
      "No GitHub token/repo connected — synthesizing a compare URL. Connect GitHub in Settings to open real PRs."
    );
  }

  const repo = ctx.repo ?? "your-org/your-repo";
  const url = `https://github.com/${repo}/compare/${build.branch}?expand=1`;
  return { number: null, url, title };
}

function brdDoc(ctx: AgentContext, brd: BrdResult): string {
  const criteria = brd.acceptanceCriteria.map((c) => `- [ ] ${c}`).join("\n");
  return `# ${ctx.request.title}

_Generated by Gauge from an approved stakeholder request._

## Overview

${brd.narrative}

## Scenarios

\`\`\`gherkin
${brd.gherkin}
\`\`\`

## Acceptance criteria

${criteria}

---
Request type: ${ctx.request.type} · BRD by: ${brd.model}
`;
}

function prBody(ctx: AgentContext, brd: BrdResult): string {
  return `Opened by **Gauge** from an approved stakeholder request.

**Request:** ${ctx.request.title}

${brd.narrative}

### Acceptance criteria
${brd.acceptanceCriteria.map((c) => `- [ ] ${c}`).join("\n")}

> This PR currently carries the approved requirements. Replace with the real
> implementation once the builder agent is wired in.`;
}
