import type { DeliverableContent } from "./kinds";

/**
 * Renders a deliverable as a fully self-contained HTML document — inline CSS,
 * no external assets — so it can be shared across teams (public share link),
 * downloaded, emailed, or printed without needing a Baton login. Light theme
 * on purpose: these travel outside the app.
 */

export interface StandaloneMeta {
  companyName: string;
  kindLabel: string;
  methodology: string;
  version: number;
  updatedAt: Date;
  requestTitle?: string | null;
}

export function renderStandaloneHtml(
  content: DeliverableContent,
  meta: StandaloneMeta
): string {
  const sections = content.sections
    .map(
      (s) => `
    <section>
      <h2>${esc(s.heading)}</h2>
      ${paragraphs(s.body)}
    </section>`
    )
    .join("\n");

  const tables = content.tables
    .map(
      (t) => `
    <section>
      ${t.title ? `<h2>${esc(t.title)}</h2>` : ""}
      <div class="table-wrap">
        <table>
          <thead><tr>${t.headers.map((h) => `<th>${esc(h)}</th>`).join("")}</tr></thead>
          <tbody>
            ${t.rows
              .map(
                (r) =>
                  `<tr>${t.headers
                    .map((_, i) => `<td>${cell(r[i] ?? "")}</td>`)
                    .join("")}</tr>`
              )
              .join("\n            ")}
          </tbody>
        </table>
      </div>
    </section>`
    )
    .join("\n");

  const date = meta.updatedAt.toISOString().slice(0, 10);

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(content.title)}</title>
<style>
  * { box-sizing: border-box; }
  body { margin: 0; background: #f4f6fa; color: #1c2330;
         font: 15px/1.6 ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
  .page { max-width: 860px; margin: 0 auto; padding: 40px 28px 64px; background: #fff;
          min-height: 100vh; border-left: 1px solid #e3e7ee; border-right: 1px solid #e3e7ee; }
  header { border-bottom: 2px solid #1c2330; padding-bottom: 18px; margin-bottom: 28px; }
  .badges { margin-bottom: 10px; }
  .badge { display: inline-block; font-size: 12px; font-weight: 600; letter-spacing: .4px;
           text-transform: uppercase; color: #3d5af1; border: 1px solid #3d5af1;
           border-radius: 999px; padding: 2px 10px; margin-right: 8px; }
  h1 { margin: 0 0 6px; font-size: 28px; line-height: 1.25; }
  .meta { color: #5b6575; font-size: 13px; }
  .summary { background: #f4f6fa; border-left: 3px solid #3d5af1; padding: 12px 16px;
             border-radius: 0 8px 8px 0; margin: 0 0 8px; }
  section { margin: 26px 0; }
  h2 { font-size: 17px; margin: 0 0 8px; border-bottom: 1px solid #e3e7ee; padding-bottom: 6px; }
  p { margin: 0 0 10px; white-space: pre-wrap; }
  .table-wrap { overflow-x: auto; }
  table { width: 100%; border-collapse: collapse; font-size: 14px; }
  th, td { text-align: left; padding: 8px 10px; border: 1px solid #e3e7ee; vertical-align: top; }
  th { background: #f4f6fa; font-size: 12.5px; text-transform: uppercase; letter-spacing: .3px; }
  tr:nth-child(even) td { background: #fafbfd; }
  footer { margin-top: 44px; padding-top: 14px; border-top: 1px solid #e3e7ee;
           color: #5b6575; font-size: 12.5px; }
  @media print { body { background: #fff; } .page { border: none; padding: 0; } }
</style>
</head>
<body>
<div class="page">
  <header>
    <div class="badges">
      <span class="badge">${esc(meta.kindLabel)}</span>
      <span class="badge">${esc(meta.methodology)}</span>
    </div>
    <h1>${esc(content.title)}</h1>
    <div class="meta">${esc(meta.companyName)}${
      meta.requestTitle ? ` · ${esc(meta.requestTitle)}` : ""
    } · v${meta.version} · ${date}</div>
  </header>
  ${content.summary ? `<p class="summary">${esc(content.summary)}</p>` : ""}
${sections}
${tables}
  <footer>Generated by Baton · ${esc(meta.kindLabel)} (${esc(meta.methodology)}) · version ${meta.version}</footer>
</div>
</body>
</html>`;
}

function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Body text → paragraphs, preserving single line breaks inside each. */
function paragraphs(body: string): string {
  return body
    .split(/\n{2,}/)
    .map((p) => `<p>${esc(p)}</p>`)
    .join("\n      ");
}

/** RACI-style single-letter cells get emphasis; everything else escapes plainly. */
function cell(value: string): string {
  const v = value.trim();
  if (/^[RACI]$/i.test(v)) return `<strong>${esc(v.toUpperCase())}</strong>`;
  return esc(v);
}
